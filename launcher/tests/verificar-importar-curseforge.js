"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { importProfile } = require("../tools/importar-curseforge");
const { syncBundledConfigs, validatePath } = require("../src/champagne-config-sync");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "champagne-import-test-"));
try {
  const projectRoot = path.join(root, "launcher"), source = path.join(root, "curseforge");
  fs.mkdirSync(path.join(projectRoot, "src"), { recursive: true });
  fs.mkdirSync(path.join(source, "config"), { recursive: true });
  fs.mkdirSync(path.join(source, "shaderpacks"), { recursive: true });
  fs.mkdirSync(path.join(source, "saves"), { recursive: true });
  fs.mkdirSync(path.join(source, "mods"), { recursive: true });
  fs.writeFileSync(path.join(source, "config", "experience.toml"), "value=1");
  fs.writeFileSync(path.join(source, "shaderpacks", "shader.zip"), "shader contents");
  fs.writeFileSync(path.join(source, "shaderpacks", "shader.zip.txt"), "download marker");
  fs.writeFileSync(path.join(source, "mods", "thirdparty.jar"), "mod");
  fs.writeFileSync(path.join(source, "saves", "level.dat"), "private world");
  let report = importProfile({ projectRoot, source, version: "0.1.0" });
  assert.equal(report.count, 2);
  assert.equal(report.backup, null);
  const instanceDir = path.join(root, "client"), metadataDir = path.join(root, "metadata");
  const run = () => syncBundledConfigs({ instanceDir, metadataDir, bundleDir: report.bundle });
  assert.equal(run().installed, 2);
  fs.writeFileSync(path.join(source, "config", "experience.toml"), "value=2");
  report = importProfile({ projectRoot, source, version: "0.1.1" });
  assert.equal(fs.readFileSync(path.join(report.backup, "champagne-defaults", "files", "config", "experience.toml"), "utf8"), "value=1");
  assert.equal(run().updated, 1);
  assert.equal(fs.readFileSync(path.join(instanceDir, "config", "experience.toml"), "utf8"), "value=2");
  fs.writeFileSync(path.join(instanceDir, "config", "experience.toml"), "my personal choice");
  fs.writeFileSync(path.join(source, "config", "experience.toml"), "value=3");
  report = importProfile({ projectRoot, source, version: "0.1.2" });
  assert.equal(run().keptModified, 1);
  assert.equal(fs.readFileSync(path.join(instanceDir, "config", "experience.toml"), "utf8"), "my personal choice");
  const manifestBefore = fs.readFileSync(path.join(report.bundle, "manifest.json"));
  fs.writeFileSync(path.join(source, "config", "hidden.jar"), "do not include jars anywhere");
  assert.throws(() => importProfile({ projectRoot, source, version: "0.1.3" }), /no permitida/);
  assert.deepEqual(fs.readFileSync(path.join(report.bundle, "manifest.json")), manifestBefore);
  assert.equal(fs.readFileSync(path.join(source, "saves", "level.dat"), "utf8"), "private world");
  for (const relative of ["config/CON.txt", "config/a./file.json", "saves/world/level.dat", "options.txt", "config/../accounts.json", "config/a.jar"]) assert.throws(() => validatePath(relative));
  console.log("OK: importa versiones, respalda defaults, actualiza experiencia, conserva cambios personales y bloquea JAR sin afectar la versión anterior.");
} finally { fs.rmSync(root, { recursive: true, force: true }); }
