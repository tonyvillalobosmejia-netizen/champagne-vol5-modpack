const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("launcher", {
  openDiscord: () => ipcRenderer.invoke("open-discord"),
  closeLauncher: () => ipcRenderer.invoke("close-launcher"),
  uninstallLauncher: () => ipcRenderer.invoke("uninstall-launcher"),
  getMemoryProfiles: () => ipcRenderer.invoke("memory-profiles"),
  repairInstallation: () => ipcRenderer.invoke("repair-installation"),
  getDiagnostics: message => ipcRenderer.invoke("diagnostics", message),
  copyDiagnostics: () => ipcRenderer.invoke("copy-diagnostics"),
  openLogs: () => ipcRenderer.invoke("open-logs"),
  onProgress: callback => ipcRenderer.on("progress", (_event, data) => callback(data)),
  getLauncherUpdateStatus:()=>ipcRenderer.invoke("launcher-update-status"),
  onLauncherUpdateStatus:callback=>ipcRenderer.on("launcher-update-state",(_event,state)=>callback(state)),
  checkLauncherUpdate:()=>ipcRenderer.invoke("check-launcher-update"),
  getAssistedStatus: () => ipcRenderer.invoke("assisted-status"),
  openAssistedPage: (relative) => ipcRenderer.invoke("assisted-open-page", relative),
  importAssistedFiles: () => ipcRenderer.invoke("assisted-import"),
  scanAssistedDownloads: () => ipcRenderer.invoke("assisted-scan-downloads"),
  installAssistedPack: () => ipcRenderer.invoke("assisted-install"),
  getAccountAvatar: () => ipcRenderer.invoke("account-avatar"),
  chooseAccountAvatar: () => ipcRenderer.invoke("choose-account-avatar"),
  resetAccountAvatar: () => ipcRenderer.invoke("reset-account-avatar"),
  getAuthStatus: () => ipcRenderer.invoke("auth-status"),
  loginDiscord: () => ipcRenderer.invoke("auth-discord-login"),
  cancelDiscordLogin: () => ipcRenderer.invoke("auth-discord-cancel"),
  registerAccount: (input) => ipcRenderer.invoke("auth-register", input),
  loginAccount: (input) => ipcRenderer.invoke("auth-login", input),
  logoutAccount: () => ipcRenderer.invoke("auth-logout"),
  prepareGame: () => ipcRenderer.invoke("prepare-game"),
  getLocalProfile: () => ipcRenderer.invoke("get-local-profile"),
  saveLocalProfile: (username) => ipcRenderer.invoke("save-local-profile", username),
  launchForge: () => ipcRenderer.invoke("launch-forge"),
  prepareWindowsNatives: () => ipcRenderer.invoke("prepare-windows-natives"),
  downloadGameFiles: () => ipcRenderer.invoke("download-game-files"),
  prepareMinecraft: () => ipcRenderer.invoke("prepare-minecraft"),
  getInfo: () => ipcRenderer.invoke("get-info"),
  installForge: () => ipcRenderer.invoke("install-forge"),
  updatePack: () => ipcRenderer.invoke("update-pack"),
  openFolder: () => ipcRenderer.invoke("open-folder"),
    getSettings: () => ipcRenderer.invoke("get-settings"),
  saveSettings: (settings) => ipcRenderer.invoke("save-settings", settings),
  onStatus: (callback) => ipcRenderer.on("status", (_event, data) => callback(data))
});
